#!/usr/bin/env python3
"""Clean up the annotation notebooks so the spec-driven generator owns 04c.

Moves (or deletes) the hand-built / obsolete scaffolding so
tools/gen_04c_notebooks.py can create a uniform set -- it skips files that
already exist, so the old ones must go first. Also writes .gitignore rules:
the 04c scaffolding is regenerable and stays OUT of the repo; the choices CSVs
and the compiled de-novo notebooks stay IN.

NEVER touches: 04_annotate_*, transfer_annotations_*, 04d_*, anything outside
notebooks/curation.

    python tools/cleanup_04c.py            # dry run (default)
    python tools/cleanup_04c.py --apply    # move to notebooks/curation/_archive/
    python tools/cleanup_04c.py --apply --delete   # actually delete
"""
import argparse, shutil, sys
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--curation", default="notebooks/curation")
ap.add_argument("--apply", action="store_true")
ap.add_argument("--delete", action="store_true", help="delete instead of archiving")
ap.add_argument("--no-gitignore", action="store_true")
a = ap.parse_args()

CUR = Path(a.curation)
if not CUR.is_dir(): sys.exit(f"not a directory: {CUR} (run from the repo root)")
ARCH = CUR/"_archive"

KEEP_PREFIX = ("04_annotate", "transfer_annotations", "04d_")     # never touched
OBSOLETE = ["04c_reannotate_mouse_epiperi.ipynb",   # un-merged: no epiperi object
            "04c_lineage_detail.ipynb",             # superseded by the generator
            "04c_reannotate_template.ipynb",        # superseded by the spec
            "04c_reannotate_immune.ipynb",          # split into per-species files
            "Untitled.ipynb"]

targets = []
for p in sorted(CUR.iterdir()):
    if p.is_dir() or p.name.startswith("."): continue
    if p.name.startswith(KEEP_PREFIX): continue
    if p.name in OBSOLETE:
        targets.append((p, "obsolete")); continue
    if p.name.startswith("04c_reannotate_") and p.suffix == ".ipynb":
        targets.append((p, "hand-built -> regenerate from spec")); continue
    if p.suffix in (".sh", ".py"):
        targets.append((p, "stray script in notebooks/")); continue

print(f"{'ARCHIVE' if not a.delete else 'DELETE'} candidates in {CUR}:")
for p, why in targets: print(f"   {p.name:46} {why}")
if not targets: print("   (none)")

kept = [p.name for p in sorted(CUR.iterdir())
        if p.is_file() and p.name.startswith(KEEP_PREFIX)]
print("\nkept untouched:")
for k in kept: print(f"   {k}")

ck = list(CUR.glob(".ipynb_checkpoints")) + list(CUR.glob("**/.ipynb_checkpoints"))
if ck: print(f"\nalso removing {len(ck)} .ipynb_checkpoints dir(s)")

GITIGNORE = """
# --- annotation pass: scaffolding is regenerable, the record is not ----------
notebooks/curation/04c_reannotate_*.ipynb   # generated by tools/gen_04c_notebooks.py
notebooks/curation/_archive/
notebooks/curation/.ipynb_checkpoints/
results/tables/clusters/                    # leiden ladder dumps, regenerable
!resources/annotations/*.csv                # the committed cluster->label record
!notebooks/public/                          # compiled de-novo notebooks
"""

if not a.apply:
    print("\n(dry run -- re-run with --apply)")
    if not a.no_gitignore: print("would append to .gitignore:\n" + GITIGNORE)
    sys.exit()

if not a.delete: ARCH.mkdir(parents=True, exist_ok=True)
for p, _ in targets:
    if a.delete: p.unlink(); print(f"  deleted  {p.name}")
    else:        shutil.move(str(p), str(ARCH/p.name)); print(f"  archived {p.name}")
for d in ck: shutil.rmtree(d, ignore_errors=True)

if not a.no_gitignore:
    gi = Path(".gitignore")
    cur = gi.read_text() if gi.exists() else ""
    if "gen_04c_notebooks.py" not in cur:
        gi.write_text(cur.rstrip("\n") + "\n" + GITIGNORE)
        print("  appended .gitignore rules")
    else:
        print("  .gitignore already has the rules")

print("\nnext:  python tools/gen_04c_notebooks.py     # regenerates all 11 from the spec")
